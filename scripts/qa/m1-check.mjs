import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1.5,reducedMotion:'reduce'});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.waitForFunction(()=>document.querySelector('[role=status]')?.textContent==='');
await page.getByRole('button',{name:'Reset view'}).click();
await page.waitForTimeout(150);
await page.screenshot({path:'docs/m1/opening-chrome.png'});
const initial=await page.locator('canvas').screenshot();
await page.locator('canvas').focus(); await page.keyboard.press('ArrowRight');
const rotated=await page.locator('canvas').screenshot();
if(initial.equals(rotated)) throw Error('Keyboard rotation unchanged');
await page.getByRole('button',{name:'Reset view'}).click();
await page.waitForTimeout(150);
const reset=await page.locator('canvas').screenshot();
if(!initial.equals(reset)) throw Error('Reset did not restore fixed view');
await page.waitForTimeout(300);
if(!reset.equals(await page.locator('canvas').screenshot())) throw Error('Reduced motion moved');
await page.getByRole('button',{name:'Zoom in',exact:true}).click();
if(reset.equals(await page.locator('canvas').screenshot())) throw Error('Zoom unchanged');
await page.getByRole('button',{name:'Reset view'}).click();
await page.mouse.move(700,450); await page.mouse.down(); await page.mouse.move(850,500,{steps:8}); await page.mouse.up();
if(reset.equals(await page.locator('canvas').screenshot())) throw Error('Drag unchanged');
const graphics=await page.evaluate(()=>{const gl=document.querySelector('canvas').getContext('webgl2');const ext=gl.getExtension('WEBGL_debug_renderer_info');return {webgl:gl.getParameter(gl.VERSION),renderer:ext?gl.getParameter(ext.UNMASKED_RENDERER_WEBGL):'unavailable'};});
await page.evaluate(()=>document.querySelector('canvas').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
await page.getByRole('heading',{name:'Graphics connection interrupted'}).waitFor();
await page.getByRole('button',{name:'Try again'}).click();
await page.waitForFunction(()=>document.querySelector('[role=status]')?.textContent==='');
await page.setViewportSize({width:390,height:844}); await page.getByRole('button',{name:'Reset view'}).click();
await page.screenshot({path:'docs/m1/mobile-chrome.png'});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow) throw Error('Horizontal overflow');
const failed=await browser.newPage();
await failed.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type==='webgl2'?null:original.call(this,type,...args)};});
await failed.goto('http://127.0.0.1:5173');await failed.getByRole('heading',{name:'This globe needs WebGL2'}).waitFor();
const asset=await browser.newPage();await asset.route('**/earth-base-2k.png',r=>r.abort());await asset.goto('http://127.0.0.1:5173');await asset.getByRole('button',{name:'Retry texture'}).waitFor();
await asset.unroute('**/earth-base-2k.png');await asset.getByRole('button',{name:'Retry texture'}).click();await asset.waitForFunction(()=>document.querySelector('[role=status]')?.textContent==='');
await fs.writeFile('docs/m1/chrome-check.json',JSON.stringify({browser:browser.version(),mode:'headless installed Chrome on M0 host',viewport:[1440,900],dpr:1.5,graphics,checks:['WebGL2 texture load','keyboard rotation','drag rotation','zoom','exact reset','reduced-motion stillness','context-loss message and rebuild','390px responsive layout','WebGL2 unavailable message','asset failure and retry'],errors},null,2)+'\n');
await browser.close();if(errors.length)throw Error(errors.join('\n')); console.log('M1 Chrome checks passed');
